import { describe, expect, it } from "vitest";
import { checkCriteria } from "@/lib/checks/criteria";
import { findCriterion, parsePrBody, parseTaskLine } from "@/lib/checks/pr-body";
import { checkTemplate } from "@/lib/checks/template";

const CRITERIA = ["slugify(null) throws a TypeError", "A new test covers non-string input", "All existing tests pass"];

const body = (over: Partial<Record<string, string>> = {}, first = "Task: PI-12") =>
  [
    first,
    "",
    "## Summary",
    over.summary ?? "- slugify throws a TypeError for anything that isn't a string",
    "",
    "## Acceptance criteria",
    over.criteria ??
      [
        "- [x] slugify(null) throws a TypeError -> src/slugify.js:8",
        "- [x] A new test covers non-string input -> tests/slugify.test.js:41",
        "- [x] All existing tests pass -> CI",
      ].join("\n"),
    "",
    "## Where to look",
    over.where ?? "- src/slugify.js:6-10: the new type check",
    "",
    "## How it was tested",
    over.tested ?? "`npm test` -> 12 passed, 0 failed",
    "",
    "## Not done or assumed",
    over.notDone ?? "- Numbers are rejected, not converted",
    "",
    "## Agent",
    over.agent ?? "Claude Code, Claude Sonnet 5.5",
  ].join("\n");

describe("the PR body parser", () => {
  it("reads the first line and the six sections", () => {
    const p = parsePrBody(body());
    expect(p.firstLine).toBe("Task: PI-12");
    expect(Object.keys(p.sections)).toEqual([
      "Summary",
      "Acceptance criteria",
      "Where to look",
      "How it was tested",
      "Not done or assumed",
      "Agent",
    ]);
    expect(p.sections["Where to look"]).toBe("- src/slugify.js:6-10: the new type check");
  });

  it("ignores Windows line breaks, a BOM and a footer after the last section", () => {
    const text = "﻿" + body().replace(/\n/g, "\r\n") + "\r\n\r\n---\r\n_Generated by [Claude Code](https://claude.ai/code)_";
    const p = parsePrBody(text);
    expect(p.firstLine).toBe("Task: PI-12");
    expect(p.sections.Agent).toBe("Claude Code, Claude Sonnet 5.5");
  });

  it("finds a criterion word for word and its pointer", () => {
    const p = parsePrBody(body());
    expect(findCriterion(p, "slugify(null) throws a TypeError")).toEqual({ ticked: true, pointer: "src/slugify.js:8" });
    expect(findCriterion(p, "slugify(null) throws")).toBeNull();
  });

  it("reads the task id from the first line", () => {
    expect(parseTaskLine("Task: PI-9\n\n## Summary")).toBe(9);
    expect(parseTaskLine("task: 9")).toBe(9);
    expect(parseTaskLine("Fixes the bug\nTask: PI-9")).toBeNull();
    expect(parseTaskLine(null)).toBeNull();
  });
});

describe("the Template check", () => {
  it("passes a PR body with the task line and every section filled", () => {
    expect(checkTemplate(body(), "PI-12")).toEqual({ name: "Template", passed: true, detail: "all sections filled" });
  });

  it("fails when the first line is not `Task: <id>` and names the problem", () => {
    const missing = checkTemplate(body({}, "Fixes slugify"), "PI-12");
    expect(missing.passed).toBe(false);
    expect(missing.detail).toBe("the first line isn't `Task: PI-12`");

    const other = checkTemplate(body({}, "Task: PI-8"), "PI-12");
    expect(other.passed).toBe(false);
    expect(other.detail).toBe("the first line names PI-8, not PI-12");
  });

  it("accepts `Task: 12` as well as `Task: PI-12`", () => {
    expect(checkTemplate(body({}, "Task: 12"), "PI-12").passed).toBe(true);
  });

  it("fails when a required section is missing or empty", () => {
    const noAgent = body().replace(/## Agent\n[\s\S]*$/, "");
    expect(checkTemplate(noAgent, "PI-12")).toEqual({ name: "Template", passed: false, detail: "missing: Agent" });

    const empty = checkTemplate(body({ where: "", notDone: "  " }), "PI-12");
    expect(empty).toEqual({ name: "Template", passed: false, detail: "empty: Where to look, Not done or assumed" });
  });

  it("counts a section that still holds the template's placeholder as empty", () => {
    const r = checkTemplate(body({ summary: "- <what changed, three bullets at most>", agent: "<agent and model used>" }), "PI-12");
    expect(r).toEqual({ name: "Template", passed: false, detail: "empty: Summary, Agent" });
  });

  it("names every problem at once", () => {
    const r = checkTemplate(body({ agent: "" }, "Fixes slugify"), "PI-12");
    expect(r.detail).toBe("the first line isn't `Task: PI-12`; empty: Agent");
  });

  it("fails an empty body", () => {
    const r = checkTemplate("", "PI-12");
    expect(r.passed).toBe(false);
    expect(r.detail).toContain("the first line isn't `Task: PI-12`");
    expect(r.detail).toContain("missing: Summary, Acceptance criteria");
  });
});

describe("the Criteria check", () => {
  it("passes when all are listed word for word and ticked", () => {
    expect(checkCriteria(body(), CRITERIA)).toEqual({ name: "Criteria", passed: true, detail: "3 of 3 listed and ticked" });
  });

  it("passes criteria without pointers, and with extra spaces", () => {
    const r = checkCriteria(
      body({ criteria: "- [X]  slugify(null)  throws a TypeError\n* [x] A new test covers non-string input → tests/a.js:1\n- [x] All existing tests pass" }),
      CRITERIA,
    );
    expect(r.passed).toBe(true);
  });

  it("fails when a brief criterion is missing", () => {
    const r = checkCriteria(body({ criteria: "- [x] slugify(null) throws a TypeError -> src/slugify.js:8\n- [x] All existing tests pass -> CI" }), CRITERIA);
    expect(r).toEqual({
      name: "Criteria",
      passed: false,
      detail: '2 of 3 listed and ticked; missing or reworded: "A new test covers non-string input"',
    });
  });

  it("fails when a criterion is reworded", () => {
    const r = checkCriteria(
      body({
        criteria:
          "- [x] slugify(null) throws TypeError -> src/slugify.js:8\n- [x] A new test covers non-string input -> tests/slugify.test.js:41\n- [x] All existing tests pass -> CI",
      }),
      CRITERIA,
    );
    expect(r.passed).toBe(false);
    expect(r.detail).toContain('missing or reworded: "slugify(null) throws a TypeError"');
  });

  it("fails when a criterion is unticked", () => {
    const r = checkCriteria(
      body({
        criteria:
          "- [x] slugify(null) throws a TypeError -> src/slugify.js:8\n- [ ] A new test covers non-string input -> tests/slugify.test.js:41\n- [x] All existing tests pass -> CI",
      }),
      CRITERIA,
    );
    expect(r).toEqual({
      name: "Criteria",
      passed: false,
      detail: '2 of 3 listed and ticked; not ticked: "A new test covers non-string input"',
    });
  });

  it("only reads the Acceptance criteria section", () => {
    const r = checkCriteria(body({ criteria: "- [x] slugify(null) throws a TypeError", where: "- [x] All existing tests pass" }), CRITERIA);
    expect(r.passed).toBe(false);
    expect(r.detail).toMatch(/^1 of 3 listed and ticked/);
  });
});

describe("the Criteria check with typesetting differences", () => {
  it("passes curly quotes, backticks, a trailing full stop and capitals", () => {
    const r = checkCriteria(
      body({ criteria: "- [x] `slugify(null)` throws a TypeError.\n- [x] A NEW TEST covers non-string input\n- [x] All existing tests pass" }),
      CRITERIA,
    );
    expect(r.passed).toBe(true);
    expect(checkCriteria(body({ criteria: "- [x] “Quoted” words" }), ['"Quoted" words']).passed).toBe(true);
  });
});
