// Reading a PR body written with the template in plan.md ("Review-friendly
// PRs"). Shared by the Template, Criteria and Evidence checks and the review
// packet, so they all read the body the same way.

export const SECTIONS = [
  "Summary",
  "Acceptance criteria",
  "Where to look",
  "How it was tested",
  "Not done or assumed",
  "Agent",
] as const;
/** Optional: a draft PR whose agent stopped to ask the owner something (plan.md, "Questions for the owner"). */
export const QUESTION_SECTION = "Question for owner";
export type SectionName = (typeof SECTIONS)[number] | typeof QUESTION_SECTION;
const KNOWN: SectionName[] = [...SECTIONS, QUESTION_SECTION];

export type ParsedBody = {
  /** The first non-blank line, trimmed. */
  firstLine: string | null;
  /** Each template section found, in the order it appears, with its text trimmed. */
  sections: Partial<Record<SectionName, string>>;
};

const normalize = (body: string | null | undefined) => (body ?? "").replace(/^﻿/, "").replace(/\r\n?/g, "\n");

/** The task id from a body whose first line is `Task: PI-9` (or `Task: 9`). */
export function parseTaskLine(body: string | null | undefined): number | null {
  const first = normalize(body)
    .split("\n")
    .find((line) => line.trim() !== "");
  const m = first && /^\s*task\s*:\s*(?:PI-)?(\d+)\s*$/i.exec(first);
  if (!m) return null;
  const id = Number(m[1]);
  return Number.isSafeInteger(id) && id > 0 ? id : null;
}

const HEADING = /^#{2}\s+(.+?)\s*#*\s*$/;
// Claude Code on the web adds "---" and a "Generated by" line after the last section.
const FOOTER = /\n\s*(?:-{3,}|\*{3,}|_{3,})\s*\n[\s\S]*$/;

export function parsePrBody(body: string | null | undefined): ParsedBody {
  const lines = normalize(body).split("\n");
  const firstLine = lines.find((l) => l.trim() !== "")?.trim() ?? null;
  const sections: ParsedBody["sections"] = {};
  let current: SectionName | null = null;
  let buffer: string[] = [];
  const flush = () => {
    if (current && sections[current] === undefined) sections[current] = buffer.join("\n");
  };
  for (const line of lines) {
    const h = HEADING.exec(line);
    if (h) {
      flush();
      const name = KNOWN.find((s) => s.toLowerCase() === h[1].toLowerCase()) ?? null;
      current = name;
      buffer = [];
    } else if (current) {
      buffer.push(line);
    }
  }
  flush();
  // The last section runs to the end of the body: drop a footer after a rule.
  const last = (Object.keys(sections) as SectionName[]).at(-1);
  if (last) sections[last] = `\n${sections[last]}`.replace(FOOTER, "");
  for (const key of Object.keys(sections) as SectionName[]) sections[key] = sections[key]!.trim();
  return { firstLine, sections };
}

/** Lines that are only a template placeholder like `- <what changed>`, or HTML comments, don't count as content. */
export function hasContent(text: string | undefined): boolean {
  if (text === undefined) return false;
  return text
    .replace(/<!--[\s\S]*?-->/g, "")
    .split("\n")
    .some((line) => line.trim() !== "" && !/^\s*(?:[-*]\s*)?<[^<>]*>\s*$/.test(line));
}

const squash = (s: string) => s.replace(/\s+/g, " ").trim();
const CHECKBOX = /^\s*[-*]\s*\[( |x|X)\]\s*(.*)$/;
const ARROW = /^\s*(?:->|→)\s*/;
const ARROWS = /\s*(?:->|→)/g;

/**
 * "Word for word" without tripping on how an agent typeset it: backticks,
 * curly or straight quotes, a trailing full stop, capitals and spacing don't
 * matter. The words themselves do.
 */
export const sameWords = (s: string) =>
  squash(
    s
      .replace(/`/g, "")
      .replace(/[“”]/g, '"')
      .replace(/[‘’]/g, "'"),
  )
    .replace(/[.;:,!]+$/, "")
    .toLowerCase();

export type CriterionLine = { ticked: boolean; pointer: string | null };

/** Where a criterion is met: lines of a file, or "CI" for tests passing in CI. */
export type Pointer = { kind: "ci" } | { kind: "lines"; path: string; start: number; end: number };

/**
 * Reads the pointer at the start of the text after a criterion's arrow:
 * `path:line`, `path:start-end` or `CI`. Anything after it is ignored. A file
 * name without a line isn't a pointer.
 */
export function parsePointer(text: string | null | undefined): Pointer | null {
  const t = (text ?? "").trim().replace(/^[`'"]+/, "");
  // "CI" alone, not a path that starts with it (ci/deploy.sh:12, CI.md:3).
  if (/^CI(?![\w./-])/i.test(t)) return { kind: "ci" };
  const m = /^(?:\.\/)?([^\s`'",:]+):(\d+)(?:\s*[-–]\s*(\d+))?/.exec(t);
  if (!m) return null;
  const a = Number(m[2]);
  const b = m[3] === undefined ? a : Number(m[3]);
  return { kind: "lines", path: m[1].replace(/^\/+/, ""), start: Math.min(a, b), end: Math.max(a, b) };
}

export const formatPointer = (p: Pointer) =>
  p.kind === "ci" ? "CI" : `${p.path}:${p.start}${p.end !== p.start ? `-${p.end}` : ""}`;

/**
 * The line in Acceptance criteria that lists `criterion` word for word (spaces
 * aside), and the pointer after its arrow, or null when it isn't listed.
 */
export function findCriterion(parsed: ParsedBody, criterion: string): CriterionLine | null {
  const want = sameWords(criterion);
  for (const line of (parsed.sections["Acceptance criteria"] ?? "").split("\n")) {
    const m = CHECKBOX.exec(line);
    if (!m) continue;
    const rest = squash(m[2]);
    // The criterion is everything before one of the arrows (a criterion may itself contain "->"), or the whole line.
    const cuts = [rest.length, ...[...rest.matchAll(ARROWS)].map((a) => a.index!)];
    for (const cut of cuts) {
      if (sameWords(rest.slice(0, cut)) !== want) continue;
      const after = rest.slice(cut).replace(ARROW, "").trim();
      return { ticked: m[1] !== " ", pointer: after || null };
    }
  }
  return null;
}
